async def seed() -> None:
    await _init_orm()

    for entry in SEED_ACTIONS:
        examples = entry.get("examples", [])
        category_names = entry.get("categories") or []
        fields = {
            "skill_key": entry.get("skill_key"),
            "icon": entry.get("icon"),
            "description": entry.get("description"),
            "sort_order": entry.get("sort_order", 0),
        }

        action = await AgentQuickAction.get_or_none(name=entry["name"])
        if action is None:
            action = await AgentQuickAction.create(name=entry["name"], visibility="public", **fields)
            print(f"  + 新功能 [{action.id}] {action.name}（{('/'.join(category_names)) or '未分类'}）")
        else:
            await action.update_from_dict(fields).save()
            print(f"  ~ 更新功能 [{action.id}] {action.name}")

        await _sync_categories(action.id, category_names)

        # 清理废弃案例（如早期未经查证的手写案例）
        for obsolete_title in entry.get("obsolete_examples", []):
            deleted = await AgentQuickActionExample.filter(action_id=action.id, title=obsolete_title).delete()
            if deleted:
                print(f"    - 删除废弃案例：{obsolete_title}")

        for ex in examples:
            exists = await AgentQuickActionExample.get_or_none(action_id=action.id, title=ex["title"])
            if exists is not None:
                print(f"    = 案例已存在，跳过：{ex['title']}")
                continue
            created = await AgentQuickActionExample.create(
                action_id=action.id,
                title=ex["title"],
                description=ex.get("description"),
                conversation_data={"messages": ex["conversation"]},
                sort_order=ex.get("sort_order", 0),
            )
            print(f"    + 案例 [{created.id}] {created.title}")

    # 各类型内按全局 sort_order 归整组内排序（橱窗组内展示顺序）
    await _renormalize_group_sort()

    from tortoise import Tortoise
    await Tortoise.close_connections()
