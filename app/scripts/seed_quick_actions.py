async def _ensure_category(name: str) -> AgentQuickActionCategory:
    """类型按 name 幂等获取；新建时排到章节末尾。"""
    cat = await AgentQuickActionCategory.get_or_none(name=name)
    if cat is not None:
        return cat
    sort = await AgentQuickActionCategory.all().count()
    cat = await AgentQuickActionCategory.create(name=name, sort_order=sort)
    print(f"  + 新类型 [{cat.id}] {name}（章节序 {sort}）")
    return cat


async def _sync_categories(action_id: int, category_names: list) -> None:
    """让功能的类型关联与清单一致（幂等）：补清单内的、删清单外的。

    组内 sort_order 此处只给追加值，最终统一在 seed() 末尾按全局排序归整。
    """
    target: dict[int, AgentQuickActionCategory] = {}
    for name in category_names:
        cat = await _ensure_category(str(name))
        target[cat.id] = cat

    links = await AgentQuickActionLink.filter(action_id=action_id).all()
    existing = {lk.category_id for lk in links}
    for lk in links:
        if lk.category_id not in target:
            await lk.delete()
            print(f"    - 解除类型关联 [{lk.category_id}]")
    for cat_id in target:
        if cat_id in existing:
            continue
        nxt = await AgentQuickActionLink.filter(category_id=cat_id).count()
        await AgentQuickActionLink.create(action_id=action_id, category_id=cat_id, sort_order=nxt)


async def _renormalize_group_sort() -> None:
    """组内排序归整：各类型内按功能的全局 sort_order 升序重排 link.sort_order。"""
    for cat in await AgentQuickActionCategory.all().order_by("sort_order", "id"):
        links = await AgentQuickActionLink.filter(category_id=cat.id).all()
        if not links:
            continue
        action_map = {
            a.id: a
            for a in await AgentQuickAction.filter(id__in=[lk.action_id for lk in links]).all()
        }

        def _key(lk: AgentQuickActionLink):
            a = action_map.get(lk.action_id)
            return (a.sort_order if a is not None else 10**9, lk.action_id)

        for i, lk in enumerate(sorted(links, key=_key)):
            if lk.sort_order != i:
                lk.sort_order = i
                await lk.save()

